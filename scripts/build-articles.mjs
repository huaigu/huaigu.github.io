import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { Marked } from 'marked';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const site = 'https://huaigu.github.io';
const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
const arrow = direction => `<svg width="18" height="18" viewBox="0 0 24 24" fill="none" aria-hidden="true"><path d="${direction === 'left' ? 'M19 12H5m6-6-6 6 6 6' : 'M5 12h14m-6-6 6 6-6 6'}" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/></svg>`;
const hrefSafe = value => {
  if (/[\u0000-\u0020\u007f]/u.test(value)) return false;
  try { return ['https:', 'http:', 'mailto:'].includes(new URL(value, site).protocol); }
  catch { return false; }
};
const sourceUrl = article => `https://github.com/huaigu/huaigu.github.io/blob/master/articles/${article.source}`;
const route = article => `/writing/${article.slug}/`;
const readTime = text => {
  const chinese = (text.match(/[\p{Script=Han}]/gu) || []).length;
  const words = (text.replace(/[\p{Script=Han}]/gu, '').match(/[\p{L}\p{N}]+/gu) || []).length;
  return Math.max(1, Math.ceil(chinese / 350 + words / 220));
};
const catalog = JSON.parse(await readFile(path.join(root, 'articles/catalog.json'), 'utf8'));
if (!Array.isArray(catalog) || !catalog.length) throw new Error('Add at least one article to articles/catalog.json.');
const seen = new Set();
for (const article of catalog) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(article.slug) || seen.has(article.slug)) throw new Error(`Invalid or duplicate article slug: ${article.slug}`);
  if (!/^[a-z0-9][a-z0-9-]*\.md$/.test(article.source)) throw new Error(`Invalid article source: ${article.source}`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(article.date) || new Date(article.date).toISOString().slice(0, 10) !== article.date) throw new Error(`Invalid article date: ${article.date}`);
  for (const field of ['title', 'summary', 'language', 'category', 'categoryEn']) {
    if (typeof article[field] !== 'string' || !article[field].trim()) throw new Error(`Missing ${field}: ${article.slug}`);
  }
  if (!['zh-CN', 'en'].includes(article.language)) throw new Error(`Unsupported article language: ${article.language}`);
  seen.add(article.slug);
  article.markdown = await readFile(path.join(root, 'articles', article.source), 'utf8');
  article.minutes = readTime(article.markdown);
}
catalog.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));

function header() {
  return `<a class="skip-link" href="#main" data-zh="跳到正文">Skip to content</a>
<header class="site-header wrap"><a class="brand" href="/" aria-label="huaigu, home" data-zh-label="huaigu，首页"><span class="brand-mark" aria-hidden="true">h<span>·</span></span>huaigu<span class="brand-slash">/</span><span class="brand-name">Alex Wang</span></a><nav aria-label="Main navigation" data-zh-label="主导航"><a href="/#work" data-zh="作品">Work</a><a href="/writing/" data-zh="文章" aria-current="page">Writing</a><a href="/#about" data-zh="关于我">About</a><a href="/#repositories" data-zh="代码仓库">Repositories</a><a class="nav-github" href="https://github.com/huaigu" target="_blank" rel="noopener noreferrer">GitHub <span aria-hidden="true">↗</span></a></nav><div class="language-switch" role="group" aria-label="Language" data-zh-label="语言" hidden><button type="button" data-language="en" lang="en" aria-pressed="true" aria-label="Switch to English" data-zh-label="切换至英文">English</button><button type="button" data-language="zh" lang="zh-CN" aria-pressed="false" aria-label="Switch to Chinese" data-zh-label="切换至中文">中文</button></div></header>`;
}
function footer() {
  return `<footer class="site-footer wrap"><a class="brand" href="/">huaigu<span class="brand-slash">/</span>Alex Wang</a><span data-zh="因好奇而创造，在开源中分享。">Built with curiosity. Shared in the open.</span><a href="#top" data-zh="回到顶部 ↑">Back to top ↑</a></footer>`;
}
